use std::{fs, io, path::Path};

pub fn normalize_path(value: &str) -> Result<String, String> {
    let path = value.strip_prefix("./").unwrap_or(value);
    if path.is_empty()
        || path.split('/').any(|part| {
            part.is_empty()
                || matches!(part, "." | "..")
                || !part
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"-_.".contains(&b))
        })
        || matches!(
            path.split('/').next(),
            Some(".sdev" | ".git" | "AGENTS.md" | ".gitignore" | "sdev.toml")
        )
    {
        return Err("--pathにはプロジェクト内の相対パスを指定してください。各名前には英数字・-・_・.を使えます。".into());
    }
    Ok(path.to_owned())
}

pub fn check_parents(root: &Path, path: &str) -> Result<(), String> {
    let mut parent = root.to_path_buf();
    let parts: Vec<_> = path.split('/').collect();
    for part in &parts[..parts.len() - 1] {
        parent.push(part);
        match fs::symlink_metadata(&parent) {
            Ok(metadata) if metadata.file_type().is_dir() => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Ok(_) => {
                return Err(format!(
                    "{}: 親には通常のディレクトリが必要です。",
                    parent.display()
                ));
            }
            Err(error) => return Err(format!("{}: {error}", parent.display())),
        }
    }
    Ok(())
}

pub fn render(path: &str) -> String {
    let root = if path.contains('/') {
        std::iter::repeat_n("..", path.matches('/').count())
            .collect::<Vec<_>>()
            .join("/")
    } else {
        ".".to_owned()
    };
    // Embed the same reviewed installer, without its top-level invocation. No
    // remote shell code is downloaded when a cloned project first starts.
    let installer = include_str!("../install.sh")
        .strip_suffix("main \"$@\"\n")
        .expect("install.sh must end with its main invocation");
    let version = env!("CARGO_PKG_VERSION");
    format!(
        r#"#!/bin/sh
# sdev bootstrap — generated by sdev {version}; commit this file.
{installer}
sdev_launch() {{
    sdev_root=$(CDPATH='' cd -- "$(dirname -- "$0")/{root}" && pwd -P) || exit 1
    case "$(uname -s)" in
        Darwin) sdev_os=macos ;;
        Linux) sdev_os=linux ;;
        *) fail 'This launcher supports macOS and Linux only' ;;
    esac
    case "$(uname -m)" in
        arm64|aarch64) sdev_arch=arm64 ;;
        x86_64|amd64) sdev_arch=x64 ;;
        *) fail 'Unsupported CPU architecture' ;;
    esac
    sdev_cache=.sdev/bin/{version}/$sdev_os-$sdev_arch
    (
        cd "$sdev_root"
        install_dir=./$sdev_cache
        check_destination
        if [ ! -e "$install_dir/sdev" ]; then
            case "${{SDEV_VERIFY:-0}}" in
                0) main --version {version} --install-dir "$install_dir" ;;
                1) main --version {version} --install-dir "$install_dir" --verify ;;
                *) fail 'SDEV_VERIFY must be 0 or 1' ;;
            esac
        fi
        [ -x "$install_dir/sdev" ] || fail 'Cached sdev is not executable; remove it and retry'
    ) >&2 || exit 1
    exec "$sdev_root/$sdev_cache/sdev" "$@"
}}
sdev_launch "$@"
"#
    )
}
