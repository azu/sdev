use std::{fs, io, path::Path};

const PLATFORMS: &[&str] = &[
    "macos-arm64",
    "macos-x64",
    "linux-arm64",
    "linux-x64",
    "windows-x64.exe",
];

pub fn checksums(version: &str, text: &str) -> Result<String, String> {
    let mut entries = std::collections::BTreeMap::new();
    for line in text.lines() {
        let (digest, asset) = line
            .split_once("  ")
            .ok_or("Invalid release checksum entry.")?;
        if digest.len() != 64
            || !digest
                .bytes()
                .all(|b| b.is_ascii_digit() || matches!(b, b'a'..=b'f'))
            || !PLATFORMS
                .iter()
                .any(|p| asset == format!("sdev-v{version}-{p}"))
            || entries
                .insert(asset.to_owned(), digest.to_owned())
                .is_some()
        {
            return Err("Invalid, duplicate, or unexpected release checksum entry.".into());
        }
    }
    if entries.len() != PLATFORMS.len() {
        return Err("Release checksums must contain all five supported targets.".into());
    }
    Ok(PLATFORMS
        .iter()
        .map(|p| {
            let asset = format!("sdev-v{version}-{p}");
            format!("{}  {asset}\n", entries[&asset])
        })
        .collect())
}

fn release_checksums() -> Result<String, String> {
    let version = env!("CARGO_PKG_VERSION");
    let text = if let Some(text) = std::env::var_os("SDEV_INIT_CHECKSUMS") {
        text.into_string()
            .map_err(|_| "Invalid UTF-8 in internal release checksums.")?
    } else {
        eprintln!("sdev: Fetching release checksums for {version}...");
        let mut text = String::new();
        for platform in PLATFORMS {
            let url = format!(
                "https://github.com/azu/sdev/releases/download/v{version}/sdev-v{version}-{platform}.sha256"
            );
            let result = std::process::Command::new("curl")
                .args(["-q", "-fsSL", "--proto", "=https", "--proto-redir", "=https", "--tlsv1.2", "--connect-timeout", "15", "--max-time", "120", &url])
                .output()
                .map_err(|e| format!("Cannot fetch release checksums: {e}. Initialization requires curl and network access."))?;
            if !result.status.success() {
                return Err(format!(
                    "Cannot fetch {url}: {}",
                    String::from_utf8_lossy(&result.stderr)
                ));
            }
            let entry = String::from_utf8(result.stdout).map_err(|e| e.to_string())?;
            // Normalize a missing final newline without joining two records.
            text.push_str(entry.trim_end_matches('\n'));
            text.push('\n');
        }
        text
    };
    checksums(version, &text)
}

pub fn normalize_path(value: &str) -> Result<String, String> {
    let path = value.strip_prefix("./").unwrap_or(value);
    if path.is_empty()
        || path.split('/').any(|part| {
            part.is_empty()
                || matches!(part, "." | "..")
                || !part
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"-_.".contains(&b))
        })
        || matches!(
            path.split('/').next(),
            Some(".sdev" | ".git" | "AGENTS.md" | ".gitignore" | "sdev.toml")
        )
    {
        return Err("--pathにはプロジェクト内の相対パスを指定してください。各名前には英数字・-・_・.を使えます。".into());
    }
    Ok(path.to_owned())
}

pub fn check_parents(root: &Path, path: &str) -> Result<(), String> {
    let mut parent = root.to_path_buf();
    let parts: Vec<_> = path.split('/').collect();
    for part in &parts[..parts.len() - 1] {
        parent.push(part);
        match fs::symlink_metadata(&parent) {
            Ok(metadata) if metadata.file_type().is_dir() => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Ok(_) => {
                return Err(format!(
                    "{}: 親には通常のディレクトリが必要です。",
                    parent.display()
                ));
            }
            Err(error) => return Err(format!("{}: {error}", parent.display())),
        }
    }
    Ok(())
}

pub fn render(path: &str) -> Result<String, String> {
    let checksums = release_checksums()?;
    let root = if path.contains('/') {
        std::iter::repeat_n("..", path.matches('/').count())
            .collect::<Vec<_>>()
            .join("/")
    } else {
        ".".to_owned()
    };
    // Embed the same reviewed installer, without its top-level invocation. No
    // remote shell code is downloaded when a cloned project first starts.
    let installer = include_str!("../install.sh")
        .strip_suffix("main \"$@\"\n")
        .expect("install.sh must end with its main invocation");
    let version = env!("CARGO_PKG_VERSION");
    Ok(format!(
        r#"#!/bin/sh
# sdev bootstrap — generated by sdev {version}; commit this file.
{installer}
sdev_pinned_checksums() {{
    cat <<'SDEV_CHECKSUMS'
{checksums}SDEV_CHECKSUMS
}}
sdev_launch() {{
    sdev_root=$(CDPATH='' cd -- "$(dirname -- "$0")/{root}" && pwd -P) || exit 1
    case "$(uname -s)" in
        Darwin) sdev_os=macos ;;
        Linux) sdev_os=linux ;;
        *) fail 'This launcher supports macOS and Linux only' ;;
    esac
    case "$(uname -m)" in
        arm64|aarch64) sdev_arch=arm64 ;;
        x86_64|amd64) sdev_arch=x64 ;;
        *) fail 'Unsupported CPU architecture' ;;
    esac
    sdev_cache=.sdev/bin/{version}/$sdev_os-$sdev_arch
    (
        cd "$sdev_root"
        install_dir=./$sdev_cache
        check_destination
        if [ ! -e "$install_dir/sdev" ]; then
            sdev_hash=$(sdev_pinned_checksums | awk -v asset="sdev-v{version}-$sdev_os-$sdev_arch" '$2 == asset {{ print $1 }}')
            case "${{SDEV_VERIFY:-0}}" in
                0) main --version {version} --install-dir "$install_dir" --sha256 "$sdev_hash" ;;
                1) main --version {version} --install-dir "$install_dir" --sha256 "$sdev_hash" --verify ;;
                *) fail 'SDEV_VERIFY must be 0 or 1' ;;
            esac
        fi
        [ -x "$install_dir/sdev" ] || fail 'Cached sdev is not executable; remove it and retry'
    ) >&2 || exit 1
    SDEV_LAUNCHER_PATH="{path}" exec "$sdev_root/$sdev_cache/sdev" "$@"
}}
sdev_launch "$@"
"#
    ))
}
