import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/review/viewer.js"],
  bundle: true,
  format: "iife",
  target: ["es2022"],
  minify: true,
  legalComments: "none", // Complete package notices are embedded separately.
  write: false,
  metafile: true,
  loader: { ".svg": "dataurl" },
  alias: {
    shiki: resolve(root, "src/review/shiki.js"),
  },
  plugins: [{
    name: "shiki-subpaths",
    setup(build) {
      // Alias only the root import. Subpaths must resolve to the real package.
      build.onResolve({ filter: /^shiki\// }, (args) => ({
        path: fileURLToPath(import.meta.resolve(args.path)),
      }));
    },
  }],
});

// Track all source and lockfile inputs, even those absent after tree shaking.
const inputs = ["pnpm-lock.yaml", "package.json", "scripts/build-review.mjs", "src/review/viewer.css"];
for (const name of Object.keys(result.metafile.inputs)) inputs.push(name);
const hash = createHash("sha256");
for (const path of [...new Set(inputs)].sort()) hash.update(path).update(await readFile(resolve(root, path)));
// Only the private-name pattern rule mistakes a public diff-mode property for
// a company name. Suppress it on affected generated lines; credential rules and
// all other lines remain checked by Secretlint.
const generated = result.outputFiles[0].text.split("\n").map((line) =>
  // secretlint-disable-next-line @secretlint/secretlint-rule-pattern
  /\bnewMode\b/.test(line)
    ? "// secretlint-disable-next-line @secretlint/secretlint-rule-pattern\n" + line
    : line,
).join("\n");
const bundle = `// Generated by scripts/build-review.mjs; inputs ${hash.digest("hex")}\n${generated}`;

// Collect full licenses for packages whose code/assets appear in the bundle.
const packages = new Map();
for (const [path, metadata] of Object.entries(Object.values(result.metafile.outputs)[0].inputs)) {
  if (!metadata.bytesInOutput || !path.includes("node_modules/")) continue;
  let directory = dirname(resolve(root, path));
  while (directory !== root && directory !== dirname(directory)) {
    try {
      const pkg = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
      if (pkg.name && pkg.version) { packages.set(`${pkg.name}@${pkg.version}`, directory); break; }
    } catch (error) { if (error.code !== "ENOENT") throw error; }
    directory = dirname(directory);
  }
}
const notices = [];
for (const [name, directory] of [...packages].sort()) {
  const files = (await readdir(directory)).filter((name) => /^(license|copying|notice|unlicense)/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing license text: ${name}`);
  notices.push(name);
  for (const file of files) notices.push(`${file}\n${await readFile(join(directory, file), "utf8")}`);
}
for (const [file, content] of [["viewer.bundle.js", bundle], ["THIRD-PARTY-NOTICES.txt", `${notices.join("\n\n").trimEnd()}\n`]]) {
  const path = resolve(root, "src/review", file);
  if (check) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Stale ${file}; run node scripts/build-review.mjs`);
  } else await writeFile(path, content);
}
console.log(`Review assets ${check ? "verified" : "built"}: ${Math.round(bundle.length / 1024)} KiB, ${packages.size} package notices`);
